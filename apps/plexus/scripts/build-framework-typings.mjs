// Collects the framework packages' .d.ts files (plus package.json) into a tracked
// TS asset that the TypeScript editor loads into Monaco as extraLibs.
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve, sep } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

export class FrameworkTypingsCollector
{
    static Packages = ['@pragmatic-tech-ai/mural', '@pragmatic-tech-ai/todl-runtime', '@pragmatic-tech-ai/todl']
    static ExtraLibRoot = 'file:///node_modules'
    static PackageJson = 'package.json'
    static DtsSuffix = '.d.ts'
    static WinSep = String.fromCharCode(92)

    constructor(fs, nodeModulesDir)
    {
        this.fs = fs
        this.nodeModulesDir = nodeModulesDir
    }

    Collect(packages)
    {
        const entries = []
        for (const pkg of packages)
        {
            const pkgDir = `${this.nodeModulesDir}/${pkg}`
            const manifest = `${pkgDir}/${FrameworkTypingsCollector.PackageJson}`
            if (!this.fs.exists(pkgDir) || !this.fs.exists(manifest))
            {
                continue
            }
            entries.push(this.MakeEntry(pkg, FrameworkTypingsCollector.PackageJson, manifest))
            for (const file of this.fs.walk(pkgDir))
            {
                const posix = file.split(FrameworkTypingsCollector.WinSep).join('/')
                if (!posix.endsWith(FrameworkTypingsCollector.DtsSuffix))
                {
                    continue
                }
                const rel = posix.substring(pkgDir.length + 1)
                entries.push(this.MakeEntry(pkg, rel, file))
            }
        }
        return entries
    }

    MakeEntry(pkg, relPath, sourcePath)
    {
        return {
            FilePath: `${FrameworkTypingsCollector.ExtraLibRoot}/${pkg}/${relPath}`,
            Content: this.fs.readText(sourcePath),
        }
    }
}

export class NodeFs
{
    static NodeModules = 'node_modules'

    exists(path)
    {
        return existsSync(path)
    }

    readText(path)
    {
        return readFileSync(path, 'utf8')
    }

    walk(dir)
    {
        const out = []
        for (const name of readdirSync(dir))
        {
            if (name === NodeFs.NodeModules)
            {
                continue
            }
            const full = join(dir, name)
            if (statSync(full).isDirectory())
            {
                out.push(...this.walk(full))
            }
            else
            {
                out.push(full)
            }
        }
        return out
    }
}

export class FrameworkTypingsCli
{
    static OutputRelPath = 'src/renderer/src/modules/typescript/framework-typings.generated.ts'
    static Header = '// GENERATED by scripts/build-framework-typings.mjs — do not edit by hand.\n// Regenerate on framework bumps: npm run typings:framework\n'
    static Interface = '\nexport interface FrameworkTypingEntry\n{\n    FilePath: string\n    Content: string\n}\n\n'
    static ConstPrefix = 'export const FrameworkTypings: readonly FrameworkTypingEntry[] = '

    // Packages are hoisted to the workspace root; fall back from app-local to there.
    static ResolveNodeModules(appDir)
    {
        const probe = FrameworkTypingsCollector.Packages[0]
        const candidates = [join(appDir, 'node_modules'), resolve(appDir, '..', '..', 'node_modules')]
        return candidates.find(c => existsSync(join(c, probe))) ?? candidates[0]
    }

    static Main()
    {
        const appDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')
        const nm = FrameworkTypingsCli.ResolveNodeModules(appDir).split(sep).join('/')
        const entries = new FrameworkTypingsCollector(new NodeFs(), nm).Collect(FrameworkTypingsCollector.Packages)
        const body = `${FrameworkTypingsCli.Header}${FrameworkTypingsCli.Interface}${FrameworkTypingsCli.ConstPrefix}${JSON.stringify(entries, null, 2)}\n`
        writeFileSync(join(appDir, FrameworkTypingsCli.OutputRelPath), body, 'utf8')
        const bytes = entries.reduce((n, e) => n + Buffer.byteLength(e.Content), 0)
        console.log(`framework typings: ${entries.length} entries, ${bytes} content bytes, file ${Buffer.byteLength(body)} bytes`)
    }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href)
{
    FrameworkTypingsCli.Main()
}
